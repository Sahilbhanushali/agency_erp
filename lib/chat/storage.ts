import { randomUUID } from "node:crypto"
import { mkdir, readFile, rm, stat, writeFile } from "node:fs/promises"
import path from "node:path"

/**
 * Where chat attachments live on disk.
 *
 * Not under public/. Everything in public/uploads is served by /api/uploads with no
 * session check at all, so a chat file put there would be readable by anyone holding
 * the URL. These are only ever served through /api/chat/attachments/[id], which checks
 * conversation membership first.
 */
export const CHAT_STORAGE_ROOT = path.resolve(
  process.env.CHAT_STORAGE_DIR || path.join(process.cwd(), "storage", "chat"),
)

/**
 * Resolves a storage key to a path, refusing anything that would land outside the
 * root. Keys are generated by newStorageKey(), but this check does not assume so.
 */
export function pathForKey(key: string): string {
  const full = path.resolve(CHAT_STORAGE_ROOT, key)
  if (full !== CHAT_STORAGE_ROOT && !full.startsWith(CHAT_STORAGE_ROOT + path.sep)) {
    throw new Error("Storage key escapes the chat storage root")
  }
  return full
}

/** yyyy/mm/<uuid>.<ext> — nothing from the uploader's filename is used. */
export function newStorageKey(ext: string): string {
  const now = new Date()
  const safeExt = ext.replace(/[^a-z0-9]/gi, "").slice(0, 8).toLowerCase()
  return `${now.getUTCFullYear()}/${String(now.getUTCMonth() + 1).padStart(2, "0")}/${randomUUID()}${safeExt ? `.${safeExt}` : ""}`
}

export async function saveFile(key: string, data: Uint8Array) {
  const full = pathForKey(key)
  await mkdir(path.dirname(full), { recursive: true })
  // "wx": never overwrite. A collision on a random UUID would be a bug worth hearing about.
  await writeFile(full, data, { flag: "wx" })
}

export async function readFileForKey(key: string): Promise<{ data: Buffer; size: number }> {
  const full = pathForKey(key)
  const [data, info] = await Promise.all([readFile(full), stat(full)])
  return { data, size: info.size }
}

export async function deleteFileForKey(key: string) {
  try {
    await rm(pathForKey(key), { force: true })
  } catch (error) {
    console.error("[chat/storage] could not delete", key, error)
  }
}
